"""Contract-neutral MCP transport client. Never interprets business envelopes."""
from __future__ import annotations

import asyncio
import json
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, AsyncContextManager, Callable, Mapping, Protocol


class MCPClientError(Exception):
    """Safe, stable code; never includes peer payloads or underlying exceptions."""
    def __init__(self, code: str):
        self.code = code
        super().__init__(code)


@dataclass(frozen=True)
class StdioConfig:
    # Trusted operator configuration only, never generated by a model/log/tool.
    command: str
    args: tuple[str, ...] = ()
    allowed_tools: frozenset[str] = frozenset()
    env: Mapping[str, str] = field(default_factory=dict, repr=False)
    connect_timeout: float = 10.0
    request_timeout: float = 10.0
    cleanup_timeout: float = 8.0
    max_result_bytes: int = 64 * 1024

    def __post_init__(self):
        if not isinstance(self.command, str) or not Path(self.command).is_absolute():
            raise MCPClientError("INVALID_CONFIG")
        if not isinstance(self.args, tuple) or any(
            not isinstance(s, str) or any(c in s for c in "\x00\r\n")
            for s in (self.command, *self.args)
        ):
            raise MCPClientError("INVALID_CONFIG")
        for value in (self.connect_timeout, self.request_timeout, self.cleanup_timeout):
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not 0 < value <= 60:
                raise MCPClientError("INVALID_CONFIG")
        if type(self.max_result_bytes) is not int or not 1024 <= self.max_result_bytes <= 1024 * 1024:
            raise MCPClientError("INVALID_CONFIG")
        allowed_env = {"PATH", "LANG", "LC_ALL", "TZ", "PYTHONIOENCODING", "PYTHONUNBUFFERED"}
        if any(k not in allowed_env or not isinstance(v, str) or "\x00" in v for k, v in self.env.items()):
            raise MCPClientError("INVALID_CONFIG")
        if not isinstance(self.allowed_tools, frozenset) or any(not isinstance(n, str) or not n for n in self.allowed_tools):
            raise MCPClientError("INVALID_CONFIG")
        # Detach from a mutable mapping supplied by the caller.
        from types import MappingProxyType
        object.__setattr__(self, "env", MappingProxyType(dict(self.env)))


@dataclass(frozen=True)
class ToolPage:
    tools: tuple[dict[str, Any], ...] = field(repr=False)
    next_cursor: str | None = field(default=None, repr=False)


@dataclass(frozen=True)
class ToolResult:
    content: tuple[dict[str, Any], ...] = field(repr=False)
    structured_content: dict[str, Any] | None = field(repr=False)
    is_error: bool


class MCPClient(Protocol):
    async def connect(self) -> None: ...
    async def disconnect(self) -> None: ...
    async def list_tools(self, cursor: str | None = None) -> ToolPage: ...
    async def call_tool(self, name: str, arguments: dict[str, Any]) -> ToolResult: ...


class Peer(Protocol):
    async def list_tools(self, cursor: str | None) -> Any: ...
    async def call_tool(self, name: str, arguments: dict[str, Any]) -> Any: ...


PeerFactory = Callable[[StdioConfig], AsyncContextManager[Peer]]


def _json_copy(value: Any, limit: int, code: str) -> Any:
    def check_keys(item):
        if isinstance(item, dict):
            if any(not isinstance(k, str) for k in item):
                raise ValueError
            for child in item.values():
                check_keys(child)
        elif isinstance(item, (list, tuple)):
            for child in item:
                check_keys(child)

    try:
        check_keys(value)
        raw = json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
        if len(raw.encode("utf-8")) > limit:
            raise MCPClientError("RESULT_TOO_LARGE" if code == "MALFORMED_RESULT" else code)
        return json.loads(raw)
    except (TypeError, ValueError, RecursionError, UnicodeError):
        raise MCPClientError(code) from None


def _wire(value: Any, limit: int) -> dict[str, Any]:
    try:
        if hasattr(value, "model_dump"):
            value = value.model_dump(mode="json", by_alias=True, exclude_none=True)
        value = _json_copy(value, limit, "MALFORMED_RESULT")
        if not isinstance(value, dict):
            raise MCPClientError("MALFORMED_RESULT")
        return value
    except MCPClientError:
        raise
    except Exception:
        raise MCPClientError("MALFORMED_RESULT") from None


def _normalize_error(exc: Exception) -> MCPClientError:
    if isinstance(exc, MCPClientError):
        return exc
    if isinstance(exc, BaseExceptionGroup):
        return _normalize_error(exc.exceptions[0])
    if isinstance(exc, TimeoutError):
        return MCPClientError("TIMEOUT")
    if isinstance(exc, (ConnectionError, EOFError, BrokenPipeError)) or type(exc).__name__ in {"EndOfStream", "ClosedResourceError", "BrokenResourceError"}:
        return MCPClientError("DISCONNECTED")
    if isinstance(exc, OSError):
        return MCPClientError("TRANSPORT_ERROR")
    if type(exc).__name__ == "ValidationError":
        return MCPClientError("MALFORMED_RESULT")
    if type(exc).__name__ == "MCPError":
        return MCPClientError("PROTOCOL_ERROR")
    return MCPClientError("TRANSPORT_ERROR")


class StdioMCPClient:
    """One operation at a time; a dedicated task owns all SDK cancel scopes.

    Timeouts/cancellation invalidate the connection. No reconnect or retry occurs.
    Factories are an injection seam for offline tests, not runtime tool input.
    """
    def __init__(self, config: StdioConfig, *, peer_factory: PeerFactory | None = None):
        if peer_factory is None:
            from .sdk import sdk_peer
            peer_factory = sdk_peer
        self.config = config
        self._factory = peer_factory
        self._owner: asyncio.Task | None = None
        self._ready: asyncio.Future | None = None
        self._pending: asyncio.Future | None = None
        self._queue: asyncio.Queue = asyncio.Queue()
        self._connected = False
        self._known: set[str] = set()
        self._failure: MCPClientError | None = None

    @property
    def connected(self) -> bool:
        return self._connected and self._owner is not None and not self._owner.done()

    async def __aenter__(self):
        await self.connect()
        return self

    async def __aexit__(self, *args):
        await self.disconnect()

    async def connect(self) -> None:
        if self._owner is not None:
            if self.connected:
                return
            raise MCPClientError("INVALID_STATE")
        self._ready = asyncio.get_running_loop().create_future()
        self._queue = asyncio.Queue()
        self._owner = asyncio.create_task(self._run(), name="mcp-stdio-owner")
        try:
            outcome = await self._wait(self._ready, self.config.connect_timeout)
            if isinstance(outcome, MCPClientError):
                await self.disconnect()
                raise outcome
        except (TimeoutError, asyncio.CancelledError) as exc:
            await self.disconnect()
            if isinstance(exc, asyncio.CancelledError):
                raise
            raise MCPClientError("TIMEOUT") from None

    async def _wait(self, future: asyncio.Future, timeout: float):
        done, _ = await asyncio.wait({future}, timeout=timeout)
        if not done:
            raise TimeoutError
        return future.result()

    async def disconnect(self) -> None:
        self._connected = False
        self._known.clear()
        if self._owner is None:
            return
        owner = self._owner
        # Only cancel once: a second cancellation could interrupt SDK teardown.
        if not owner.done() and not owner.cancelling():
            owner.cancel()
        done, _ = await asyncio.wait({owner}, timeout=self.config.cleanup_timeout)
        if not done:
            # Keep ownership reference; refuse reuse while cleanup is outstanding.
            raise MCPClientError("CLEANUP_TIMEOUT")
        if not owner.cancelled():
            owner.result()
        if self._owner is owner:
            self._owner = None
        if self._failure is not None:
            failure, self._failure = self._failure, None
            raise failure

    async def _run(self):
        try:
            async with self._factory(self.config) as peer:
                self._connected = True
                self._ready.set_result(None)
                while True:
                    operation, values, reply = await self._queue.get()
                    try:
                        if operation == "list":
                            raw = await peer.list_tools(*values)
                        else:
                            raw = await peer.call_tool(*values)
                        if not reply.done():
                            reply.set_result(raw)
                    except Exception as exc:
                        if not reply.done():
                            reply.set_result(_normalize_error(exc))
                        break  # A failed transport is never reused implicitly.
        except asyncio.CancelledError:
            pass
        except Exception as exc:
            self._failure = _normalize_error(exc)
        finally:
            self._connected = False
            failure = self._failure or MCPClientError("DISCONNECTED")
            if self._ready is not None and not self._ready.done():
                self._ready.set_result(failure)
            if self._pending is not None and not self._pending.done():
                self._pending.set_result(failure)

    async def _request(self, operation: str, *values):
        if not self.connected:
            raise MCPClientError("NOT_CONNECTED")
        if self._pending is not None:
            raise MCPClientError("BUSY")
        reply = self._pending = asyncio.get_running_loop().create_future()
        self._queue.put_nowait((operation, values, reply))
        try:
            result = await self._wait(reply, self.config.request_timeout)
            if isinstance(result, MCPClientError):
                await self.disconnect()
                raise result
            return _wire(result, self.config.max_result_bytes)
        except (TimeoutError, asyncio.CancelledError) as exc:
            await self.disconnect()
            if isinstance(exc, asyncio.CancelledError):
                raise
            raise MCPClientError("TIMEOUT") from None
        finally:
            self._pending = None

    async def list_tools(self, cursor: str | None = None) -> ToolPage:
        if cursor is not None and (not isinstance(cursor, str) or not cursor or len(cursor) > 4096):
            raise MCPClientError("INVALID_ARGUMENTS")
        raw = await self._request("list", cursor)
        tools, next_cursor = raw.get("tools"), raw.get("nextCursor")
        if not isinstance(tools, list) or len(tools) > 1024 or (next_cursor is not None and (not isinstance(next_cursor, str) or not next_cursor or len(next_cursor) > 4096)):
            raise MCPClientError("MALFORMED_RESULT")
        names = set()
        for tool in tools:
            if not isinstance(tool, dict) or not isinstance(tool.get("name"), str) or not tool["name"] or tool["name"] in names or not isinstance(tool.get("inputSchema"), dict):
                raise MCPClientError("MALFORMED_RESULT")
            if "outputSchema" in tool and not isinstance(tool["outputSchema"], dict):
                raise MCPClientError("MALFORMED_RESULT")
            names.add(tool["name"])
        # Discovery is descriptive, not authorization. Allowlist is independent.
        if cursor is None:
            self._known.clear()
        self._known.update(names)
        return ToolPage(tuple(tools), next_cursor)

    async def call_tool(self, name: str, arguments: dict[str, Any]) -> ToolResult:
        if not isinstance(name, str) or name not in self.config.allowed_tools or name not in self._known:
            raise MCPClientError("TOOL_NOT_ALLOWED")
        if not isinstance(arguments, dict) or any(not isinstance(k, str) for k in arguments):
            raise MCPClientError("INVALID_ARGUMENTS")
        arguments = _json_copy(arguments, self.config.max_result_bytes, "INVALID_ARGUMENTS")
        raw = await self._request("call", name, arguments)
        if raw.get("resultType", "complete") != "complete":
            raise MCPClientError("UNSUPPORTED_RESULT")
        content = raw.get("content")
        structured = raw.get("structuredContent")
        error = raw.get("isError", False)
        if not isinstance(content, list) or (structured is not None and not isinstance(structured, dict)) or type(error) is not bool:
            raise MCPClientError("MALFORMED_RESULT")
        for block in content:
            if not isinstance(block, dict) or not isinstance(block.get("type"), str) or (block["type"] == "text" and not isinstance(block.get("text"), str)):
                raise MCPClientError("MALFORMED_RESULT")
        return ToolResult(tuple(content), structured, error)
