"""Application-only synthetic coordinator candidate, not a wire contract/binder.

No default model, executor, registry, redactor or evidence interpreter. Production
Adapter/SDK integration is deliberately absent pending contract handoff/review.
"""
from __future__ import annotations
import asyncio
from dataclasses import dataclass, field, replace
import json
import math
import time
from typing import Callable, Protocol


@dataclass(frozen=True)
class Evidence:
    id: str
    source: str
    text: str = field(repr=False)


@dataclass(frozen=True)
class Observation:
    evidence: tuple[Evidence, ...] = ()
    limited: bool = False
    note: str = field(default="", repr=False)


@dataclass(frozen=True)
class Decision:
    tool: str | None = None
    arguments: dict = field(default_factory=dict, repr=False)
    conclusion: str = field(default='', repr=False)
    citations: tuple[str, ...] = ()


@dataclass(frozen=True)
class Report:
    status: str
    conclusion: str = field(default='', repr=False)
    evidence: tuple[Evidence, ...] = field(default=(), repr=False)
    citations: tuple[str, ...] = ()
    tool_calls: int = 0
    llm_turns: int = 0
    cleanup_pending: bool = False
    execution_state: str = "not_dispatched"
    conclusion_verified: bool = False


class DecisionSource(Protocol):
    async def choose(self, question: str, observations: tuple[Observation, ...]) -> Decision: ...


class Executor(Protocol):
    async def execute(self, name: str, arguments: dict): ...
    async def finish_cleanup(self) -> None: ...


class _DeadlineExpired(Exception):
    pass


class _CleanupPending(Exception):
    code = 'CLEANUP_TIMEOUT'
    execution_state = 'unknown'

    def __init__(self, cancelled=False):
        self.cancelled = cancelled
        super().__init__('CLEANUP_TIMEOUT')


class Coordinator:
    """Single-use owner; executor owns request timeout and SDK cleanup.

    choose() must be cancellation-cooperative async code. Do not wrap the sync
    Ollama adapter in a thread and claim cancellation. interpret() is trusted app
    code, never generated by an LLM; no SCRUM-12 field parsing occurs here.
    """
    def __init__(self, model: DecisionSource, executor: Executor, *, read_only: frozenset[str],
                 scope_allows: Callable, interpret: Callable, redact: Callable,
                 max_tools=8, max_turns=6, seconds=120, max_bytes=65536,
                 clock=time.monotonic, cleanup_seconds=8):
        if (type(read_only) is not frozenset or not read_only
                or any(type(n) is not str or not n for n in read_only)
                or 'restart_service' in read_only
                or type(max_tools) is not int or not 1 <= max_tools <= 8
                or type(max_turns) is not int or not 1 <= max_turns <= 6
                or type(seconds) not in (int, float) or not math.isfinite(seconds) or not 0 < seconds <= 120
                or type(cleanup_seconds) not in (int, float)
                or not math.isfinite(cleanup_seconds) or not 0 < cleanup_seconds <= 60
                or type(max_bytes) is not int or not 1024 <= max_bytes <= 65536
                or not all(callable(x) for x in (scope_allows, interpret, redact, clock))):
            raise ValueError('INVALID_CONFIG')
        self.model, self.executor = model, executor
        self.read_only, self.scope_allows = read_only, scope_allows
        self.interpret, self.redact, self.clock = interpret, redact, clock
        self.max_tools, self.max_turns, self.seconds, self.max_bytes = max_tools, max_turns, seconds, max_bytes
        self.report: Report | None = None
        self._started = False
        self._cleanup_pending = False
        self.cleanup_seconds = cleanup_seconds
        self._operation: asyncio.Task | None = None
        self._running = False
        self._joining = False
        self._states = []

    @property
    def state(self):
        return self._states[-1] if self._states else None

    @property
    def state_history(self):
        return tuple(self._states)

    def _transition(self, state):
        self._states.append(state)

    def _executor_pending(self):
        return getattr(self.executor, 'cleanup_state', 'idle') in {'pending', 'unconfirmed'}

    async def _join_operation(self):
        # Never propagate repeated caller cancellation into the owned dispatch.
        deadline = time.monotonic() + self.cleanup_seconds
        cancelled = False
        while not self._operation.done():
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                self._cleanup_pending = True
                raise _CleanupPending(cancelled) from None
            try:
                await asyncio.wait({self._operation}, timeout=remaining)
            except asyncio.CancelledError:
                cancelled = True
        return cancelled

    def _consume_operation(self):
        task, self._operation = self._operation, None
        try:
            return task.result(), None
        except (Exception, asyncio.CancelledError) as error:
            return None, error

    async def _dispatch(self, name, arguments, remaining):
        self._operation = asyncio.create_task(
            self.executor.execute(name, arguments), name='scrum24-dispatch')
        expired = cancelled = False
        try:
            done, _ = await asyncio.wait({self._operation}, timeout=remaining)
            expired = not done
        except asyncio.CancelledError:
            cancelled = True
        if expired or cancelled:
            # One cancellation asks Bridge to stop; Bridge retains its own owner.
            if not self._operation.done() and not self._operation.cancelling():
                self._operation.cancel()
            try:
                cancelled |= await self._join_operation()
            except _CleanupPending as pending:
                if cancelled or pending.cancelled:
                    raise asyncio.CancelledError from None
                raise
        result, error = self._consume_operation()
        self._cleanup_pending = self._executor_pending()
        if cancelled:
            raise asyncio.CancelledError from None
        if self._cleanup_pending:
            raise _CleanupPending() from None
        if error is not None:
            if expired:
                raise _DeadlineExpired() from None
            raise error
        # A response won the deadline race: return it for fail-closed sanitization.
        return result, expired

    def _clean(self, text):
        if type(text) is not str or len(text.encode('utf-8')) > self.max_bytes:
            raise ValueError('DATA_POLICY')
        result = self.redact(text)
        if type(result) is not str or len(result.encode('utf-8')) > self.max_bytes:
            raise ValueError('DATA_POLICY')
        return result

    def _safe_observation(self, result, previous):
        """Validate/redact before storing either an on-time or a late result."""
        try:
            observation = self.interpret(result)
            if (not isinstance(observation, Observation)
                    or type(observation.evidence) is not tuple
                    or type(observation.limited) is not bool):
                return 'invalid_evidence', None, previous
            pending = {}
            for item in observation.evidence:
                if (not isinstance(item, Evidence) or type(item.id) is not str or not item.id
                        or len(item.id) > 128 or type(item.source) is not str or not item.source
                        or len(item.source) > 256 or item.id in pending):
                    return 'invalid_evidence', None, previous
                if self._clean(item.id) != item.id:
                    return 'invalid_evidence', None, previous
                safe = Evidence(item.id, self._clean(item.source), self._clean(item.text))
                if safe.source != item.source or (item.id in previous and previous[item.id] != safe):
                    return 'invalid_evidence', None, previous
                pending[item.id] = safe
            merged = {**previous, **pending}
            if len(json.dumps([vars(e) for e in merged.values()], ensure_ascii=False).encode()) > self.max_bytes:
                return 'output_limit', None, previous
            safe_observation = Observation(tuple(pending.values()), observation.limited,
                                           self._clean(observation.note))
            return None, safe_observation, merged
        except Exception:
            return 'data_policy', None, previous

    async def finish_cleanup(self):
        """Rejoin retained work; never reconnect or resend a tool."""
        if self._running or self._joining:
            raise ValueError('BUSY')
        self._joining = True
        cancelled = False
        late_result = None
        late_success = False
        self._cleanup_pending = True
        try:
            if self._operation is not None:
                cancelled = await self._join_operation()
                late_result, late_error = self._consume_operation()
                late_success = late_error is None
            # Preserve safe evidence independently of cleanup confirmation. A
            # later cleanup failure must not discard an already received result.
            if late_success and self.report is not None:
                previous = {item.id: item for item in self.report.evidence}
                code, _, merged = self._safe_observation(late_result, previous)
                status = ('budget_exhausted' if self.report.status == 'cleanup_pending'
                          else self.report.status)
                self.report = replace(self.report, status=code or status,
                                      evidence=tuple(merged.values()),
                                      execution_state='response_received')
            await self.executor.finish_cleanup()
        except (Exception, asyncio.CancelledError) as error:
            if self.report is not None:
                self.report = replace(self.report, cleanup_pending=True)
            if isinstance(error, asyncio.CancelledError) or getattr(error, 'cancelled', False):
                raise asyncio.CancelledError from None
            raise RuntimeError('CLEANUP_UNCONFIRMED') from None
        finally:
            self._joining = False
        self._cleanup_pending = False
        if self.report is not None:
            self.report = replace(self.report, cleanup_pending=False)
        if cancelled:
            raise asyncio.CancelledError

    async def run(self, question: str) -> Report:
        if self._started:
            raise ValueError('SINGLE_USE')
        self._started = True
        self._running = True
        self._transition('RECEIVED')
        deadline = self.clock() + self.seconds
        observations, evidence, seen = [], {}, set()
        calls = turns = repairs = 0
        execution_state = "not_dispatched"

        def finish(status, conclusion='', citations=()):
            terminal = {'concluded': 'CONCLUDED', 'limited': 'CONCLUDED',
                        'cancelled': 'CANCELLED', 'budget_exhausted': 'BUDGET_EXHAUSTED'}.get(status, 'ERROR')
            self._transition(terminal)
            self._transition('REPORTED')
            self.report = Report(status, conclusion, tuple(evidence.values()), citations,
                                 calls, turns, self._cleanup_pending, execution_state)
            return self.report

        try:
            question = self._clean(question)
            while True:
                remaining = deadline - self.clock()
                if remaining <= 0 or turns >= self.max_turns:
                    return finish('budget_exhausted')
                self._transition('ANALYZING')
                turns += 1
                try:
                    decision = await asyncio.wait_for(self.model.choose(question, tuple(observations)), remaining)
                except TimeoutError:
                    return finish('budget_exhausted')
                # No dispatch or further reasoning after a decision used up time.
                if self.clock() >= deadline:
                    return finish('budget_exhausted')
                if not isinstance(decision, Decision):
                    repairs += 1
                    if repairs > 2:
                        return finish('invalid_decision')
                    continue
                if decision.tool is None:
                    if (type(decision.citations) is not tuple or not decision.citations
                            or any(type(x) is not str or x not in evidence for x in decision.citations)):
                        return finish('insufficient_evidence')
                    conclusion = self._clean(decision.conclusion)
                    if not conclusion.strip():
                        return finish('insufficient_evidence')
                    if self.clock() >= deadline:
                        return finish('budget_exhausted')
                    limited = any(o.limited for o in observations)
                    if limited:
                        conclusion = 'không đủ bằng chứng để kết luận; dữ liệu bị giới hạn, có thể do quyền truy cập.'
                    return finish('limited' if limited else 'concluded', conclusion, decision.citations)
                if type(decision.tool) is not str or decision.tool not in self.read_only:
                    return finish('policy_denied')
                if calls >= self.max_tools:
                    return finish('budget_exhausted')
                if type(decision.arguments) is not dict:
                    return finish('invalid_arguments')
                # JSON finite/bounded; authoritative schema validation remains ToolBridge.
                encoded = json.dumps(decision.arguments, sort_keys=True, allow_nan=False, ensure_ascii=False)
                if len(encoded.encode()) > self.max_bytes:
                    return finish('invalid_arguments')
                arguments = json.loads(encoded)
                if self.scope_allows(decision.tool, arguments) is not True:
                    return finish('policy_denied')
                fingerprint = (decision.tool, encoded, tuple(evidence))
                if fingerprint in seen:
                    return finish('repeated_call')
                seen.add(fingerprint)
                if self.clock() >= deadline:
                    return finish('budget_exhausted')
                self._transition('COLLECTING')
                calls += 1
                execution_state = "unknown"
                try:
                    remaining = deadline - self.clock()
                    if remaining <= 0:
                        calls -= 1
                        execution_state = 'not_dispatched'
                        return finish('budget_exhausted')
                    result, dispatch_expired = await self._dispatch(decision.tool, arguments, remaining)
                except _DeadlineExpired:
                    return finish('budget_exhausted')
                except Exception as error:
                    # Stable allowlist only; no peer payload/exception strings in report.
                    code = getattr(error, 'code', '')
                    state = getattr(error, 'execution_state', 'unknown')
                    execution_state = state if state in {'not_dispatched', 'unknown', 'response_received'} else 'unknown'
                    if code in {'CLEANUP_TIMEOUT', 'CLEANUP_PENDING', 'CLEANUP_FAILED'}:
                        self._cleanup_pending = True
                        return finish('cleanup_pending')
                    return finish({'TIMEOUT': 'tool_timeout', 'DISCONNECTED': 'disconnected',
                                   'INVALID_ARGUMENTS': 'invalid_arguments', 'WRITE_NOT_ALLOWED': 'policy_denied',
                                   'DATA_POLICY': 'data_policy', 'RESULT_TOO_LARGE': 'output_limit',
                                   'BUDGET_EXHAUSTED': 'budget_exhausted'}.get(code, 'tool_error'))
                execution_state = "response_received"
                code, next_observation, merged = self._safe_observation(result, evidence)
                if code:
                    return finish(code)
                evidence = merged
                bounded_history = observations + [next_observation]
                if len(json.dumps([{'evidence': [vars(e) for e in o.evidence], 'limited': o.limited, 'note': o.note} for o in bounded_history], ensure_ascii=False).encode()) > self.max_bytes:
                    return finish('output_limit')
                observations.append(next_observation)
                if dispatch_expired or getattr(result, 'budget_exhausted', False) or self.clock() >= deadline:
                    return finish('budget_exhausted')
        except asyncio.CancelledError:
            self._cleanup_pending = self._operation is not None or self._executor_pending()
            finish('cancelled')
            raise asyncio.CancelledError from None
        except Exception:
            return finish('data_policy')
        finally:
            self._running = False
